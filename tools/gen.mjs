// Builds src/names.ts, src/attributes.ts and src/entities.ts from the C# sources of z3l.FastHtmlParser,
// so that the JS port uses exactly the same tag list, attribute names and HTML5 entity table.
//
//   node tools/gen.mjs <path to z3l.FastHtmlParser/src/z3l.FastHtmlParser>
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const src = process.argv[2];
if (!src) {
  console.error('usage: node tools/gen.mjs <path to src/z3l.FastHtmlParser>');
  process.exit(2);
}
const out = new URL('../src/', import.meta.url);

// the member names of a C# enum without explicit values, in order
function enumMembers(path, name) {
  const text = readFileSync(path, 'utf8');
  let body = text.slice(text.indexOf('public enum ' + name));
  body = body.slice(body.indexOf('{') + 1, body.lastIndexOf('}'));
  const members = [];
  for (let line of body.split('\n')) {
    const comment = line.indexOf('//');
    if (comment >= 0) line = line.slice(0, comment);
    line = line.trim().replace(/,$/, '').trim();
    if (line) members.push(line);
  }
  return members;
}

const header = (from) => `// Code generated by tools/gen.mjs from ${from}; DO NOT EDIT.\n\n`;

// ----- tags -----
const specialTags = { Comment: '!--', Doctype: '!doctype', XmlDeclaration: '?xml' };
const tags = enumMembers(join(src, 'HtmlTag.cs'), 'HtmlTag');
let names = header('HtmlTag.cs');
names += '/** Known tag names: HTML (incl. obsolete), SVG, MathML and common XML (RSS, Atom, sitemap). */\n';
names += 'export const Tag = {\n';
tags.forEach((m, i) => (names += `  ${m}: ${i},\n`));
names += '} as const;\n\n';
names += '/** A known tag: a value of `Tag`. */\nexport type Tag = (typeof Tag)[keyof typeof Tag];\n\n';
names += `export const tagCount = ${tags.length};\n\n`;
names += '/** The lower-case name of each `Tag`. */\nexport const tagNames: readonly string[] = [\n';
for (const m of tags) names += `  ${JSON.stringify(specialTags[m] ?? m.toLowerCase())},\n`;
names += '];\n';
writeFileSync(new URL('names.ts', out), names);

// ----- attributes -----
const htmlNames = readFileSync(join(src, 'Core', 'HtmlNames.cs'), 'utf8');
const specialAttributes = {};
for (const m of htmlNames.matchAll(/HtmlAttribute\.(\w+) => "([^"]+)"/g)) specialAttributes[m[1]] = m[2];
let attrs = header('HtmlAttribute.cs and HtmlNames.cs');
attrs += '/** Common HTML / SVG / XML attribute names, for `attr`, `attrRaw`, `Query.attr` and the shortcuts.\n';
attrs += ' * Any other name works as a plain string. */\nexport const Attr = {\n';
const seen = new Set();
for (const m of enumMembers(join(src, 'HtmlAttribute.cs'), 'HtmlAttribute')) {
  const name = specialAttributes[m] ?? m.toLowerCase();
  if (seen.has(name)) throw new Error('duplicate attribute name ' + name);
  seen.add(name);
  attrs += `  ${m}: ${JSON.stringify(name)},\n`;
}
attrs += '} as const;\n';
writeFileSync(new URL('attributes.ts', out), attrs);

// ----- entities -----
// the concatenated string literals of `name = "..." + "...";`, escapes left as written
function constant(text, name) {
  const start = text.indexOf(name + ' =');
  const end = start + text.slice(start).indexOf(';');
  let s = '';
  for (const m of text.slice(start, end).matchAll(/"((?:[^"\\]|\\.)*)"/g)) s += m[1];
  return s;
}
// C# escapes (\uXXXX, \0) into a JS string
function unescape(s) {
  return s.replace(/\\u([0-9a-fA-F]{4})|\\0/g, (m, hex) => (hex ? String.fromCharCode(parseInt(hex, 16)) : '\0'));
}
const table = readFileSync(join(src, 'Core', 'HtmlEntities.Table.cs'), 'utf8');
const entityNames = constant(table, 'private const string Names').split(/\s+/).filter(Boolean);
const values = unescape(constant(table, 'private const string Values'));
if (values.length !== 2 * entityNames.length) throw new Error(`${entityNames.length} names, ${values.length} value units`);
let maxName = 0;
let maxLegacy = 0;
for (const n of entityNames) {
  const legacy = n.startsWith('+');
  const name = legacy ? n.slice(1) : n;
  maxName = Math.max(maxName, name.length);
  if (legacy) maxLegacy = Math.max(maxLegacy, name.length);
}
// JS string literal with every non-ASCII or control unit escaped
const js = (s) => {
  let out = '"';
  for (let i = 0; i < s.length; i++) {
    const u = s.charCodeAt(i);
    out += u < 0x20 || u > 0x7e || s[i] === '"' || s[i] === '\\' ? '\\u' + u.toString(16).padStart(4, '0') : s[i];
  }
  return out + '"';
};
let ent = header('HtmlEntities.Table.cs');
ent += '// HTML5 named character references (without "&" and ";"), space-separated; "+" marks the legacy ones,\n';
ent += '// which are also recognized without ";". Each value is two UTF-16 units, the second "\\0" when it is one char.\n';
ent += `export const entityNames =\n  ${js(entityNames.join(' '))};\n\n`;
ent += `export const entityValues =\n  ${js(values)};\n\n`;
ent += `export const entityMaxName = ${maxName};\nexport const entityMaxLegacyName = ${maxLegacy};\n`;
writeFileSync(new URL('entities.ts', out), ent);

console.log(`${tags.length} tags, ${seen.size} attributes, ${entityNames.length} entities`);
