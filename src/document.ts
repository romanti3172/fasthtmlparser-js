function find(nodes: readonly HtmlNode[], first: number, end: number, q: Query): HtmlNode | null {
  for (let i = first; i < nodes.length; i++) {
    const n = nodes[i];
    if (n.end > end) break;
    if (q.matches(n)) return n;
  }
  return null;
}

function findAll(nodes: readonly HtmlNode[], first: number, end: number, q: Query): HtmlNode[] {
  const out: HtmlNode[] = [];
  for (let i = first; i < nodes.length; i++) {
    const n = nodes[i];
    if (n.end > end) break;
    if (q.matches(n)) out.push(n);
  }
  return out;
}

// ----- queries -----

const hasClassBit = 1;
const hasIdBit = 2;
const hasAttrBit = 4;
const hasTextBit = 8;
const hasIdStartsWith = 16;
const hasTextStartsWith = 32;
const hasBody = 64;
const hasBodyStartsWith = 128;
const hasSource = 256;

/**
 * Selects tags by name and, optionally, class, id, attribute value, visible text, inner HTML and the source of the
 * opening tag. Queries are immutable: every method returns a new one. Start with `by(Tag.Div)`, `by("my-widget")`
 * or `any()`.
 */
export class Query {
  /** @internal Tag+1, 0: by name or any */
  private readonly key: number;
  /** @internal */
  private readonly tagName: string;
  /** @internal */
  private readonly has: number;
  /** @internal */
  private readonly values: readonly string[];

  /** @internal use by(), byName() or any() */
  constructor(key: number, tagName: string, has = 0, values: readonly string[] = emptyValues) {
    this.key = key;
    this.tagName = tagName;
    this.has = has;
    this.values = values;
  }

  private with(bit: number, slot: number, value: string, slot2 = -1, value2 = ''): Query {
    const values = this.values.length ? this.values.slice() : new Array<string>(valueSlots).fill('');
    values[slot] = value;
    if (slot2 >= 0) values[slot2] = value2;
    return new Query(this.key, this.tagName, this.has | bit, values);
  }

  /** Adds a class criterion: one of the space-separated classes, case-insensitive. */
  class(cls: string): Query {
    return this.with(hasClassBit, slotClass, cls);
  }

  /** Adds an id criterion. */
  id(id: string): Query {
    return this.with(hasIdBit, slotId, id);
  }

  /** Adds an attribute criterion: the decoded value equals value. */
  attr(name: string, value: string): Query {
    return this.with(hasAttrBit, slotAttr, name, slotAttrValue, value);
  }

  /** Adds a visible-text criterion (see `HtmlNode.text()`). */
  text(text: string): Query {
    return this.with(hasTextBit, slotText, text);
  }

  /** Adds a criterion: the decoded id starts with prefix. */
  idStartsWith(prefix: string): Query {
    return this.with(hasIdStartsWith, slotIdStartsWith, prefix);
  }

  /** Adds a criterion: the visible text starts with prefix. */
  textStartsWith(prefix: string): Query {
    return this.with(hasTextStartsWith, slotTextStartsWith, prefix);
  }

  /** Adds a criterion: the inner HTML (trimmed) equals body. */
  body(body: string): Query {
    return this.with(hasBody, slotBody, body);
  }

  /** Adds a criterion: the inner HTML (trimmed) starts with prefix. */
  bodyStartsWith(prefix: string): Query {
    return this.with(hasBodyStartsWith, slotBodyStartsWith, prefix);
  }

  /** Adds a criterion: the opening tag without '<' and '>' (see `HtmlNode.source()`) equals source. */
  source(source: string): Query {
    return this.with(hasSource, slotSource, source);
  }

  /** Whether the tag matches every criterion. */
  matches(n: HtmlNode | null | undefined): boolean {
    if (n == null) return false;
    if (this.key !== 0) {
      if (n.key !== this.key - 1 && (n.key >= 0 || this.tagName === '' || !equalFold(n.custom, this.tagName))) return false;
    } else if (this.tagName !== '' && !equalFold(n.name, this.tagName)) {
      return false;
    }
    const has = this.has;
    if (has === 0) return true;
    const v = this.values;
    if (has & hasIdBit && (v[slotId] === '' || !attrEquals(attrRaw(n, 'id'), v[slotId]))) return false;
    if (has & hasAttrBit && !attrEquals(attrRaw(n, v[slotAttr]), v[slotAttrValue])) return false;
    if (has & hasClassBit && !hasClass(n, v[slotClass])) return false;
    if (has & hasIdStartsWith && !attrStartsWith(attrRaw(n, Attr.Id), v[slotIdStartsWith])) return false;
    if (has & hasSource && n.source() !== v[slotSource]) return false;
    if (has & hasBody && n.body() !== v[slotBody]) return false;
    if (has & hasBodyStartsWith && !n.body().startsWith(v[slotBodyStartsWith])) return false;
    // the text last: it is the most expensive check
    if (has & hasTextBit && !isText(n.body(), v[slotText], () => n.text())) return false;
    if (has & hasTextStartsWith && !n.text().startsWith(v[slotTextStartsWith])) return false;
    return true;
  }
}

const slotClass = 0;
const slotId = 1;
const slotAttr = 2;
const slotAttrValue = 3;
const slotText = 4;
const slotIdStartsWith = 5;
const slotTextStartsWith = 6;
const slotBody = 7;
const slotBodyStartsWith = 8;
const slotSource = 9;
const valueSlots = 10;
const emptyValues: readonly string[] = [];

/** Selects tags with a known name (`Tag.Div`) or any name ("my-widget"), case-insensitively. */
export function by(name: TagName): Query {
  return typeof name === 'number' ? new Query(name + 1, '') : byName(name);
}

/** Selects tags by name, case-insensitively; it works for names that are not in `Tag`. */
export function byName(name: string): Query {
  const t = lookupTag(name);
  return t >= 0 ? new Query(t + 1, name) : new Query(0, name);
}

const anyQuery = new Query(0, '');

/** Selects every tag. */
export function any(): Query {
  return anyQuery;
}

// The older "optional" shortcuts skip an empty criterion.
function optClass(q: Query, cls: string): Query {
  return cls === '' ? q : q.class(cls);
}
function optId(q: Query, id: string): Query {
  return id === '' ? q : q.id(id);
}
function optText(q: Query, text: string): Query {
  return text === '' ? q : q.text(text);
}
function optBody(q: Query, body: string): Query {
  return body === '' ? q : q.body(body);
}

/** The tags of the list at the level of the first one (the outermost tags of a findAll result). */
export function firstLevel(nodes: readonly HtmlNode[]): HtmlNode[] {
  return level(nodes, null);
}

/** The tags of the list with the name, at the level of the first tag of the list. */
export function firstLevelByName(nodes: readonly HtmlNode[], name: TagName): HtmlNode[] {
  return level(nodes, by(name));
}

/** The tags of the list with the name and the class, at the level of the first tag of the list. */
export function firstLevelByNameClass(nodes: readonly HtmlNode[], name: TagName, cls: string): HtmlNode[] {
  return level(nodes, by(name).class(cls));
}

function level(nodes: readonly HtmlNode[], q: Query | null): HtmlNode[] {
  if (nodes.length === 0) return [];
  const depth = nodes[0].depth;
  return nodes.filter((n) => n.depth === depth && (q === null || q.matches(n)));
}

/** The visible text of an HTML fragment, as `HtmlNode.text()` gives it for a tag's content. */
